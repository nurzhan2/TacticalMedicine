using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

namespace FieldMedic.EditorTools
{
    /// <summary>
    /// Static performance budget check of the Main scene → docs/PERF.md: total triangles, triangles visible from
    /// the player's spot (worst of 8 headings, frustum-culled by renderer bounds), draw-call estimate (static
    /// batching merges static renderers per material; dynamic renderers × sub-meshes; particles/lines), lights,
    /// shadow casters and texture memory (ASTC 6×6 estimate with mips).
    /// Batch: -executeMethod FieldMedic.EditorTools.PerfReport.Run
    /// </summary>
    public static class PerfReport
    {
        const int TriBudget = 150000, DrawBudget = 120;

        [MenuItem("FieldMedic/Perf Report")]
        public static void Run()
        {
            EditorSceneManager.OpenScene("Assets/Scenes/Main.unity", OpenSceneMode.Single);
            var renderers = Object.FindObjectsByType<Renderer>(FindObjectsSortMode.None).Where(r => r.enabled && r.gameObject.activeInHierarchy).ToArray();

            long totalTris = 0;
            foreach (var r in renderers) totalTris += Tris(r);

            // visible from the player's spot (eye 1.6 m at origin), worst heading
            long worstVisible = 0; int worstDraws = 0; float worstYaw = 0f;
            var cam = new GameObject("~perfcam").AddComponent<Camera>();
            cam.fieldOfView = 100f; cam.aspect = 1f; cam.nearClipPlane = 0.03f; cam.farClipPlane = 120f;
            for (int i = 0; i < 8; i++)
            {
                cam.transform.SetPositionAndRotation(new Vector3(0f, 1.6f, 0f), Quaternion.Euler(10f, i * 45f, 0f));
                var planes = GeometryUtility.CalculateFrustumPlanes(cam);
                var vis = renderers.Where(r => GeometryUtility.TestPlanesAABB(planes, r.bounds)).ToArray();
                long tris = vis.Sum(r => (long)Tris(r));
                int draws = EstimateDraws(vis);
                if (tris > worstVisible) { worstVisible = tris; worstYaw = i * 45f; }
                worstDraws = Mathf.Max(worstDraws, draws);
            }
            Object.DestroyImmediate(cam.gameObject);
            int allDraws = EstimateDraws(renderers);

            var lights = Object.FindObjectsByType<Light>(FindObjectsInactive.Include, FindObjectsSortMode.None);
            int shadowLights = lights.Count(l => l.shadows != LightShadows.None);
            int realtimeActive = lights.Count(l => l.enabled && l.gameObject.activeInHierarchy);

            var textures = new HashSet<Texture>();
            foreach (var r in renderers)
                foreach (var m in r.sharedMaterials)
                {
                    if (m == null) continue;
                    foreach (var name in m.GetTexturePropertyNames())
                    {
                        var t = m.GetTexture(name);
                        if (t != null) textures.Add(t);
                    }
                }
            double texMB = 0;
            var texLines = new List<string>();
            foreach (var t in textures.OrderByDescending(t => t.width * t.height))
            {
                int w = t.width, h = t.height;
                var path = AssetDatabase.GetAssetPath(t);
                var ti = AssetImporter.GetAtPath(path) as TextureImporter;
                if (ti != null) { int max = ti.maxTextureSize; float s = Mathf.Min(1f, (float)max / Mathf.Max(w, h)); w = (int)(w * s); h = (int)(h * s); }
                double mb = w * h * 3.56 / 8.0 * 1.333 / (1024.0 * 1024.0);
                texMB += mb;
                if (texLines.Count < 25) texLines.Add($"| {Path.GetFileName(path)} | {w}×{h} | {mb:F2} |");
            }

            var sb = new StringBuilder();
            sb.AppendLine("# Performance report — Main scene (Quest 3S budget)");
            sb.AppendLine();
            sb.AppendLine($"Generated by `PerfReport.Run` (editor static analysis; verify with OVR Metrics Tool on device).");
            sb.AppendLine();
            sb.AppendLine("| Metric | Value | Budget | Status |");
            sb.AppendLine("|---|---|---|---|");
            sb.AppendLine($"| Triangles visible from the player spot (worst heading {worstYaw:F0}°, 100° FOV) | {worstVisible:N0} | {TriBudget:N0} | {(worstVisible <= TriBudget ? "OK" : "OVER")} |");
            sb.AppendLine($"| Triangles in scene (all) | {totalTris:N0} | — | info |");
            sb.AppendLine($"| Draw calls estimate, worst view (static batching per material) | {worstDraws} | {DrawBudget} | {(worstDraws <= DrawBudget ? "OK" : "OVER")} |");
            sb.AppendLine($"| Draw calls estimate, whole scene | {allDraws} | — | info |");
            sb.AppendLine($"| Renderers | {renderers.Length} | — | info |");
            sb.AppendLine($"| Lights (all / enabled at start) | {lights.Length} / {realtimeActive} | 1 main + few small | info |");
            sb.AppendLine($"| Shadow-casting lights | {shadowLights} | 1 | {(shadowLights <= 1 ? "OK" : "OVER")} |");
            sb.AppendLine($"| Texture memory (ASTC 6×6 est., {textures.Count} textures) | {texMB:F1} MB | ≤ 2K textures | {(textures.All(t => t.width <= 2048) ? "OK" : "check")} |");
            sb.AppendLine();
            sb.AppendLine("Notes: the moon/flare directional light is the only shadow caster (the flare *steers* it, no extra shadow maps). " +
                          "Flash lights (4 pooled point lights), the red headlamp (spot) and the dugout candle are unshadowed. " +
                          "Particles: dirt/smoke/debris/dust/sparks/rain systems are pooled and idle most of the time.");
            sb.AppendLine();
            sb.AppendLine("## Largest textures");
            sb.AppendLine("| Texture | Size (import) | MB |");
            sb.AppendLine("|---|---|---|");
            foreach (var l in texLines) sb.AppendLine(l);
            Directory.CreateDirectory("docs");
            File.WriteAllText("docs/PERF.md", sb.ToString());
            Debug.Log($"[FMVR] perf: visible tris {worstVisible}, total tris {totalTris}, draws worst {worstDraws}, shadows {shadowLights}, tex {texMB:F1} MB");
            if (Application.isBatchMode) EditorApplication.Exit(0);
        }

        static int Tris(Renderer r)
        {
            Mesh m = null;
            if (r is SkinnedMeshRenderer smr) m = smr.sharedMesh;
            else if (r is MeshRenderer) { var mf = r.GetComponent<MeshFilter>(); if (mf != null) m = mf.sharedMesh; }
            else if (r is LineRenderer lr) return Mathf.Max(0, lr.positionCount - 1) * 2;
            if (m == null) return 0;
            long t = 0;
            for (int i = 0; i < m.subMeshCount; i++) t += m.GetIndexCount(i) / 3;
            return (int)t;
        }

        static int EstimateDraws(IEnumerable<Renderer> rs)
        {
            var staticMats = new HashSet<Material>();
            int dynamic = 0;
            foreach (var r in rs)
            {
                bool isStatic = GameObjectUtility.AreStaticEditorFlagsSet(r.gameObject, StaticEditorFlags.BatchingStatic);
                if (r is ParticleSystemRenderer || r is LineRenderer) { dynamic++; continue; }
                foreach (var m in r.sharedMaterials)
                {
                    if (m == null) continue;
                    if (isStatic) staticMats.Add(m); else dynamic++;
                }
            }
            return staticMats.Count + dynamic;
        }
    }
}
